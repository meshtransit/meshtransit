package selfhost

import (
	"path/filepath"
	"strings"
)

const (
	backupService        = "backup"
	backupServiceUnit    = "meshtransit-backup.service"
	backupTimerUnit      = "meshtransit-backup.timer"
	backupScript         = "meshtransit-backup.sh"
	backupEgressNetwork  = "meshtransit-egress"
	backupCaddyDataMount = "/caddy-data"
)

// backupServiceSettings is the "backup" maintenance service: the Core image
// as root with DAC_READ_SEARCH only (compose.go), reading the database
// stream on stdin and the files read-only, writing only the backup and
// textfile directories. It has no network unless it uploads to S3, and
// then only its own. Logging is off: its stdin carries the database (never
// logged by Docker), its stdout one JSON summary.
func backupServiceSettings(config Config, layout Layout, settings Backup) map[string]any {
	stateDir := filepath.Dir(layout.SecretsDir)
	volumes := []any{
		existingBind(layout.SecretsDir, true), existingBind(filepath.Join(stateDir, ".setup.lock"), false),
		existingBind(OperatorDir, true), existingBind(settings.Dir, false),
		map[string]any{"type": "volume", "source": "caddy-data", "target": backupCaddyDataMount, "read_only": true},
	}
	if settings.TextfileDir != "" {
		volumes = append(volumes, existingBind(settings.TextfileDir, false))
	}
	service := map[string]any{
		"image": config.Images.Core, "user": "0:0", "restart": "no", "profiles": []string{"maintenance"},
		"command":    []string{"setup", "backup", "--db-stdin", "--state-dir=" + stateDir},
		"volumes":    volumes,
		"stdin_open": true,
		// The unit's Nice/IOSchedulingClass do not reach containers: the
		// container gets a low CPU weight, and pg_basebackup a transfer cap
		// (--max-rate) on PostgreSQL's side.
		"cpu_shares": 256,
		"logging":    map[string]string{"driver": "none"},
	}
	if settings.S3 != nil {
		service["networks"] = []string{backupEgressNetwork}
	} else {
		service["network_mode"] = "none"
	}
	return service
}

// backupUnits are the host's service, timer and script. Each night the
// database's base backup streams from PostgreSQL's own socket (docker
// compose exec: exec output never reaches a log driver) into the backup
// service's stdin; bash's pipefail fails the run when either side fails.
// ExecStopPost records a failed run, so even one that never reached the
// container shows in the metrics. The script lives in run/ (root's,
// readable by the image group: no container user can change what root
// runs), which also keeps shell quoting out of systemd's own parser.
func backupUnits(layout Layout) map[string][]byte {
	compose := docker + " compose -f " + filepath.Join(layout.RunDir, "compose.yaml")
	password := filepath.Join(layout.SecretsDir, "postgres-superuser-password")
	script := strings.Join([]string{
		"#!/usr/bin/env bash",
		"# Generated by meshcore setup render; the backup unit runs it. Do not edit.",
		"set -euo pipefail",
		`if [ "${1:-}" = record-failure ]; then`,
		`  [ "${SERVICE_RESULT:-}" = success ] && exit 0`,
		// A timeout kills only the docker CLI: stop the backup's container
		// too, so it cannot finish and report success after this failure.
		`  ids=$(docker ps -q --filter label=com.docker.compose.project=meshtransit --filter label=com.docker.compose.service=` +
			backupService + `)`,
		`  [ -z "$ids" ] || docker kill $ids >/dev/null 2>&1 || true`,
		"  exec " + compose + " --profile maintenance run --rm -T " + backupService +
			" setup backup --record-failure --state-dir=" + filepath.Dir(layout.SecretsDir) + " </dev/null",
		"fi",
		// sh inside the PostgreSQL container: the password reaches only
		// pg_basebackup's environment.
		compose + ` exec -T postgres sh -c 'PGPASSWORD="$(cat ` + password +
			`)" exec pg_basebackup -h /var/run/postgresql -U postgres -D - -Ft -X fetch --checkpoint=fast --max-rate=64M' |`,
		"  " + compose + " --profile maintenance run --rm -T " + backupService,
		"",
	}, "\n")
	scriptPath := filepath.Join(layout.RunDir, backupScript)
	service := strings.Join([]string{
		"# Generated by meshcore setup render. Install a copy: docs runbooks/backup-restore.md.",
		"[Unit]",
		"Description=MeshTransit: back up the databases, secrets and certificates",
		"Requires=docker.service",
		"After=docker.service",
		"",
		"[Service]",
		"Type=oneshot",
		"Nice=10",
		"IOSchedulingClass=idle",
		"TimeoutStartSec=4h",
		"ExecStart=/usr/bin/bash " + scriptPath,
		"ExecStopPost=/usr/bin/bash " + scriptPath + " record-failure",
		"",
	}, "\n")
	timer := strings.Join([]string{
		"# Generated by meshcore setup render. Install a copy: docs runbooks/backup-restore.md.",
		"[Unit]",
		"Description=MeshTransit: back up each night",
		"",
		"[Timer]",
		"OnCalendar=*-*-* 02:15:00",
		"Persistent=true",
		"RandomizedDelaySec=10min",
		"",
		"[Install]",
		"WantedBy=timers.target",
		"",
	}, "\n")
	return map[string][]byte{backupServiceUnit: []byte(service), backupTimerUnit: []byte(timer),
		backupScript: []byte(script)}
}
