package selfhost

import (
	"path/filepath"
	"strings"
)

// The host's systemd units that renew the internal TLS (renew.go). setup
// render writes them to run/ (root's, so no container user can change what
// root runs); the operator installs a copy (docs:
// runbooks/self-host-setup.md) and installs it again when an upgrade
// changes them.
const (
	renewServiceUnit = "meshtransit-tls-renew.service"
	renewTimerUnit   = "meshtransit-tls-renew.timer"
	renewService     = "renew-tls"
	// Bare names: systemd (239+) and sh look them up in the standard paths,
	// where docker-ce installs docker (/usr/bin) and others (/usr/local/bin).
	docker = "docker"
	// flock waits for a setup run that holds the lock; the unit's
	// TimeoutStopSec bounds the wait (no -w: busybox's flock lacks it).
	flock = "flock"
)

// renewUnits are the service and timer: each day at 03:00, and a few
// minutes after each boot (a crash between two renames is then repaired
// before the next night), renew-tls runs in its container. Then, holding
// the setup lock so no setup run queues a restart this one would remove,
// the services the restart file names restart one by one, datastores
// first. The restart runs even when renewal failed, for what an earlier
// run changed. The file is removed only when every restart succeeded; a
// name outside the known services is refused, so the file can never make
// root run anything else. Both phases have a time limit, so a hung docker
// fails the run instead of holding the timer forever.
func renewUnits(layout Layout) map[string][]byte {
	stateDir := filepath.Dir(layout.SecretsDir)
	compose := docker + " compose -f " + filepath.Join(layout.RunDir, "compose.yaml")
	restartFile := filepath.Join(restartDir(layout.SecretsDir), RestartFile)
	// systemd expands $ and %: $$ and %% reach the shell as $ and %.
	script := strings.Join([]string{
		"f=" + restartFile,
		`[ -s "$$f" ] || exit 0`,
		`set -- $$(cat -- "$$f")`,
		`for s in "$$@"; do case "$$s" in ` + strings.Join(restartOrder, "|") +
			`) ;; *) echo "unknown service $$s" >&2; exit 1;; esac; done`,
		// Each service is up (healthy, where it has a check) before the next
		// restarts: Core does not start against a PostgreSQL still starting.
		// No --no-deps: compose v2.40 restarts only the named service (checked
		// in dind), and an older compose without the flag would fail every
		// restart; at worst a dependency restarts too (migrate is idempotent).
		`for s in "$$@"; do ` + compose + ` restart "$$s" && ` + compose +
			` up -d --no-deps --no-recreate --wait "$$s" || exit 1; done`,
		`rm -f -- "$$f"`,
	}, "; ")
	service := strings.Join([]string{
		"# Generated by meshcore setup render. Install a copy: docs runbooks/self-host-setup.md.",
		"[Unit]",
		"Description=MeshTransit: renew the server's internal TLS certificates",
		"Requires=docker.service",
		"After=docker.service",
		"",
		"[Service]",
		"Type=oneshot",
		"TimeoutStartSec=15min",
		"TimeoutStopSec=15min",
		"ExecStart=" + compose + " --profile maintenance run --rm --no-TTY " + renewService,
		"ExecStopPost=" + flock + " " + filepath.Join(stateDir, ".setup.lock") +
			" /bin/sh -c '" + script + "'",
		"",
	}, "\n")
	timer := strings.Join([]string{
		"# Generated by meshcore setup render. Install a copy: docs runbooks/self-host-setup.md.",
		"[Unit]",
		"Description=MeshTransit: renew the server's internal TLS certificates each day",
		"",
		"[Timer]",
		"OnCalendar=*-*-* 03:00:00",
		"OnBootSec=5min",
		"Persistent=true",
		"RandomizedDelaySec=10min",
		"",
		"[Install]",
		"WantedBy=timers.target",
		"",
	}, "\n")
	return map[string][]byte{renewServiceUnit: []byte(service), renewTimerUnit: []byte(timer)}
}
