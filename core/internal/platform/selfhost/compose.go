// DataDirs are the bundled datastores' data directories under the state
// directory; the setup command creates them owned by the image user.
var DataDirs = []string{"postgres", "redis"}

// Fixed addresses on the server's private network. Docker hands out
// dynamic addresses only from the upper half (ipRange), so no container can
// be given the proxy's trusted address, or the migrate container's, which
// alone may log in as PostgreSQL's superuser.
const (
	ipRange        = "172.30.0.128/25"
	migrateAddress = "172.30.0.12"
	coreAddress    = "172.30.0.13"
	postgresIP     = "172.30.0.14"
	redisIP        = "172.30.0.15"
	relayAddress   = "172.30.0.16"
)

// serviceMounts are the files each Core container may read: exactly the
// paths its settings name. Only migrate holds the superuser's password, and
// no container holds the CA key.
type serviceMounts struct {
	core, migrate []string
}

// composeFiles are the files of the one-server installation: compose.yaml,
// the proxy's Caddyfile, PostgreSQL's pg_hba.conf and the Console's env.
func composeFiles(config Config, layout Layout, mounts serviceMounts, connections int) (map[string][]byte, error) {
	secret := func(name string) string { return filepath.Join(layout.SecretsDir, name) }
	console, err := envFile(map[string]string{
		"MESH_CONSOLE_LISTEN_HOST":         "0.0.0.0",
		"MESH_CONSOLE_LISTEN_PORT":         "8443",
		"MESH_CONSOLE_ORIGIN":              consoleOrigin(config),
		"MESHCORE_UPSTREAM":                "https://login." + internalDomain + ":9443",
		"MESHCORE_CA_FILE":                 secret("ca.crt"),
		"MESH_CONSOLE_TLS_CERT_FILE":       secret("console.crt"),
		"MESH_CONSOLE_TLS_KEY_FILE":        secret("console.key"),
		"MESH_CONSOLE_TRUSTED_PROXY_CIDRS": trustedProxy,
	})
	if err != nil {
		return nil, fmt.Errorf("console.env: %w", err)
	}
	compose, err := composeYAML(config, layout, mounts, connections)
	if err != nil {
		return nil, err
	}
	// The superuser only from the migrate container; each login role only
	// to its own database; anything else (mesh_observer too) matches no line
	// and is refused.
	hba := strings.Join([]string{
		"# Generated by meshcore setup.",
		"local all all scram-sha-256",
		"hostssl " + coreDatabase + " postgres " + migrateAddress + "/32 scram-sha-256",
		"hostssl " + coreDatabase + " mesh_migrator,mesh_runtime,mesh_worker " + privateSubnet + " scram-sha-256",
		"hostssl " + identityDatabase + " identity_migrator," + IdentityRuntimeRole + " " + privateSubnet +
			" scram-sha-256",
		"",
	}, "\n")
	return map[string][]byte{
		"compose.yaml": compose, "Caddyfile": caddyfile(config, layout), "pg_hba.conf": []byte(hba),
		"console.env": console,
	}, nil
}

// readOnly mounts each path at itself, read only.
func readOnly(paths ...string) []string {
	mounts := make([]string, 0, len(paths))
	for _, path := range paths {
		mounts = append(mounts, path+":"+path+":ro")
	}
	return mounts
}

func composeYAML(config Config, layout Layout, mounts serviceMounts, connections int) ([]byte, error) {
	stateDir := filepath.Dir(layout.SecretsDir)
	secret := func(name string) string { return filepath.Join(layout.SecretsDir, name) }
	run := func(name string) string { return filepath.Join(layout.RunDir, name) }
	// Core and the relay reach the public names through the proxy on the
	// private network, not out and back in through the public address.
	publicNames := []string{config.Domain + ":" + proxyAddress, config.IdentityHost() + ":" + proxyAddress}
	operator := OperatorDir + ":" + OperatorDir + ":ro"
	network := func(address string, aliases ...string) map[string]any {
		attachment := map[string]any{"ipv4_address": address}
		if len(aliases) > 0 {
			attachment["aliases"] = aliases
		}
		return map[string]any{"meshtransit": attachment}
	}
	services := map[string]any{
		"postgres": map[string]any{
			"image": postgresImage, "user": imageUserID, "restart": "unless-stopped",
			"environment": map[string]string{
				"POSTGRES_PASSWORD_FILE": secret("postgres-superuser-password"),
				"PGDATA":                 "/var/lib/postgresql/data/pgdata",
			},
			"command": []string{"postgres", "-c", "ssl=on", "-c", "ssl_cert_file=" + secret("postgres.crt"),
				"-c", "ssl_key_file=" + secret("postgres.key"), "-c", "hba_file=" + run("pg_hba.conf"),
				"-c", "password_encryption=scram-sha-256",
				// Sized for one server (docs: runbooks/self-host-setup.md): the
				// connection count Core's pools need, the default 128 MB of
				// shared buffers, and vacuum memory that cannot spike.
				"-c", "max_connections=" + strconv.Itoa(connections),
				"-c", "shared_buffers=128MB",
				"-c", "autovacuum_work_mem=32MB",
				"-c", "maintenance_work_mem=64MB"},
			"volumes": append([]string{filepath.Join(stateDir, "postgres") + ":/var/lib/postgresql/data",
				secret("postgres-init.sql") + ":/docker-entrypoint-initdb.d/10-meshtransit.sql:ro"},
				readOnly(secret("postgres-superuser-password"), secret("postgres.crt"), secret("postgres.key"),
					run("pg_hba.conf"))...),
			"healthcheck": map[string]any{"test": []string{"CMD", "pg_isready", "-h", "/var/run/postgresql",
				"-U", "postgres", "-d", "postgres"}, "interval": "5s", "timeout": "5s", "retries": 30},
			"networks": network(postgresIP, "postgres."+internalDomain),
		},
		"redis": map[string]any{
			"image": redisImage, "user": imageUserID, "restart": "unless-stopped",
			"command": []string{"redis-server", "--port", "0", "--tls-port", "6379",
				"--tls-cert-file", secret("redis.crt"), "--tls-key-file", secret("redis.key"),
				"--tls-ca-cert-file", secret("ca.crt"), "--tls-auth-clients", "no",
				"--aclfile", secret("redis-users.acl"), "--dir", "/data", "--appendonly", "yes"},
			"volumes": append([]string{filepath.Join(stateDir, "redis") + ":/data"},
				readOnly(secret("redis.crt"), secret("redis.key"), secret("ca.crt"), secret("redis-users.acl"))...),
			"networks": network(redisIP, "redis."+internalDomain),
		},
		"migrate": map[string]any{
			"image": config.Images.Core, "user": imageUserID, "restart": "no",
			"command":    []string{"setup", "migrate", "--state-dir=" + stateDir},
			"volumes":    append(readOnly(mounts.migrate...), operator),
			"depends_on": map[string]any{"postgres": map[string]string{"condition": "service_healthy"}},
			"networks":   network(migrateAddress),
		},
		"meshcore": map[string]any{
			"image": config.Images.Core, "user": imageUserID, "restart": "unless-stopped",
			"command": []string{"serve"}, "env_file": []string{run("core.env")},
			"volumes": append(readOnly(mounts.core...), operator),
			"depends_on": map[string]any{
				"migrate": map[string]string{"condition": "service_completed_successfully"},
				"redis":   map[string]string{"condition": "service_started"},
			},
			"networks": network(coreAddress, "api."+internalDomain, "control."+internalDomain,
				"login."+internalDomain),
			"extra_hosts": publicNames,
		},
		"console": map[string]any{
			"image": config.Images.Console, "user": imageUserID, "restart": "unless-stopped",
			"env_file":   []string{run("console.env")},
			"volumes":    readOnly(secret("console.crt"), secret("console.key"), secret("ca.crt")),
			"depends_on": map[string]any{"meshcore": map[string]string{"condition": "service_started"}},
			"networks":   network(consoleAddress, "console."+internalDomain),
		},
		"caddy": map[string]any{
			"image": caddyImage, "restart": "unless-stopped",
			"ports": []string{"80:80", "443:443"},
			"volumes": append([]string{run("Caddyfile") + ":/etc/caddy/Caddyfile:ro", "caddy-data:/data",
				"caddy-config:/config"}, readOnly(secret("ca.crt"))...),
			"networks": network(proxyAddress),
		},
		"relay": map[string]any{
			"image": config.Images.Relay, "user": imageUserID, "restart": "unless-stopped",
			"command": []string{"serve"}, "env_file": []string{run("relay.env")},
			"volumes": readOnly(secret("relay.key")),
			"ports": []string{
				strconv.Itoa(relayUDPPort) + ":" + strconv.Itoa(relayUDPPort) + "/udp",
				strconv.Itoa(relaySTUNPort) + ":" + strconv.Itoa(relaySTUNPort) + "/udp",
				strconv.Itoa(relaySTUNAltPort) + ":" + strconv.Itoa(relaySTUNAltPort) + "/udp",
			},
			"depends_on":  map[string]any{"caddy": map[string]string{"condition": "service_started"}},
			"networks":    network(relayAddress),
			"extra_hosts": publicNames,
		},
	}
	// No container keeps a capability it does not need or gains one later.
	// The proxy binds 80 and 443 and runs with the image group to read its
	// 0640 files; the relay's binary carries NET_BIND_SERVICE as a file
	// capability (its image binds low ports elsewhere), which the kernel
	// refuses to exec when the bounding set lacks it.
	for name, service := range services {
		settings := service.(map[string]any)
		settings["cap_drop"] = []string{"ALL"}
		settings["security_opt"] = []string{"no-new-privileges:true"}
		switch name {
		case "caddy":
			settings["user"] = "0:65532"
			settings["cap_add"] = []string{"NET_BIND_SERVICE"}
		case "relay":
			settings["cap_add"] = []string{"NET_BIND_SERVICE"}
		}
	}
	contents, err := yaml.Marshal(map[string]any{
		"name":     "meshtransit",
		"services": services,
		"networks": map[string]any{"meshtransit": map[string]any{
			"ipam": map[string]any{"config": []map[string]string{{"subnet": privateSubnet, "ip_range": ipRange}}},
		}},
		"volumes": map[string]any{"caddy-data": map[string]any{}, "caddy-config": map[string]any{}},
	})
	if err != nil {
		return nil, fmt.Errorf("%w: compose: %w", ErrInvalidConfig, err)
	}
	return append([]byte("# Generated by meshcore setup render; do not edit.\n"), contents...), nil
}

// caddyfile routes the public names like the POC's ingress: node control
// and relay documents to control, browser registration to the login
// listener, everything else to the Console, and the identity host to the
// broker. Upstreams are verified with the server's own CA.
func caddyfile(config Config, layout Layout) []byte {
	ca := filepath.Join(layout.SecretsDir, "ca.crt")
	upstream := func(address, serverName string) string {
		return "reverse_proxy https://" + address + " {\n\t\t\ttransport http {\n\t\t\t\ttls_trust_pool file " + ca +
			"\n\t\t\t\ttls_server_name " + serverName + "\n\t\t\t}\n\t\t}"
	}
	global := "\temail " + config.ACMEEmail
	if config.ACMEEmail == "" {
		global = "\tlocal_certs"
	}
	var builder strings.Builder
	builder.WriteString("# Generated by meshcore setup render; do not edit.\n{\n" + global + "\n}\n\n")
	builder.WriteString(config.Domain + " {\n")
	builder.WriteString("\t@control path /mtcp/v1* /relay/v1*\n\thandle @control {\n\t\t" +
		upstream("control."+internalDomain+":8443", "control."+internalDomain) + "\n\t}\n")
	builder.WriteString("\t@register path /register/v1*\n\thandle @register {\n\t\t" +
		upstream("login."+internalDomain+":9443", config.Domain) + "\n\t}\n")
	builder.WriteString("\thandle {\n\t\t" + upstream("console."+internalDomain+":8443", "console."+internalDomain) +
		"\n\t}\n}\n\n")
	builder.WriteString(config.IdentityHost() + " {\n\t" +
		strings.ReplaceAll(upstream("meshcore:9444", config.IdentityHost()), "\n\t\t", "\n\t") + "\n}\n")
	return []byte(builder.String())
}
