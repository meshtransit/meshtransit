package intake

import (
	"errors"
	"time"

	"github.com/meshtransit/meshtransit/internal/enrollment"
	"github.com/meshtransit/meshtransit/internal/enrollment/registration"
	"github.com/meshtransit/meshtransit/internal/publicid"
)

var (
	// ErrInvalidChange reports an incomplete pending-intent mutation.
	ErrInvalidChange = errors.New("registration intake: invalid change")
	// ErrInvalidEvidenceIDs reports missing or aliased audit/outbox identities.
	ErrInvalidEvidenceIDs = errors.New("registration intake: invalid evidence IDs")
)

// EvidenceIDs identifies the authority change, audit event, and outbox event
// belonging to one pending-intent mutation.
type EvidenceIDs struct {
	changeID      publicid.ID
	auditEventID  publicid.ID
	outboxEventID publicid.ID
}

// NewEvidenceIDs validates distinct UUIDv7 identities generated by the application.
func NewEvidenceIDs(
	changeID publicid.ID,
	auditEventID publicid.ID,
	outboxEventID publicid.ID,
) (EvidenceIDs, error) {
	ids := EvidenceIDs{
		changeID:      changeID,
		auditEventID:  auditEventID,
		outboxEventID: outboxEventID,
	}
	if !ids.IsValid() {
		return EvidenceIDs{}, ErrInvalidEvidenceIDs
	}
	return ids, nil
}

// ChangeID returns the authority-mutation correlation identity.
func (ids EvidenceIDs) ChangeID() publicid.ID { return ids.changeID }

// AuditEventID returns the immutable audit event identity.
func (ids EvidenceIDs) AuditEventID() publicid.ID { return ids.auditEventID }

// OutboxEventID returns the durable outbox event identity.
func (ids EvidenceIDs) OutboxEventID() publicid.ID { return ids.outboxEventID }

// IsValid reports whether all evidence identities are distinct and usable.
func (ids EvidenceIDs) IsValid() bool {
	return ids.changeID.IsValid() && ids.auditEventID.IsValid() && ids.outboxEventID.IsValid() &&
		ids.changeID != ids.auditEventID && ids.changeID != ids.outboxEventID &&
		ids.auditEventID != ids.outboxEventID
}

// Change is one fully validated pending-registration plus its audit/outbox evidence.
type Change struct {
	command      registration.Command
	registration enrollment.Registration
	requestHash  registration.RequestHash
	evidenceIDs  EvidenceIDs
	occurredAt   time.Time
}

// NewChange validates one replayable pending-intent mutation.
func NewChange(
	command registration.Command,
	pending enrollment.Registration,
	requestHash registration.RequestHash,
	evidenceIDs EvidenceIDs,
	occurredAt time.Time,
) (Change, error) {
	change := Change{
		command:      command,
		registration: pending,
		requestHash:  requestHash,
		evidenceIDs:  evidenceIDs,
		occurredAt:   occurredAt.UTC(),
	}
	if !change.IsValid() {
		return Change{}, ErrInvalidChange
	}
	return change, nil
}

// Command returns the authenticated registration command represented by the intent.
func (change Change) Command() registration.Command { return change.command }

// Registration returns the pending durable state to insert.
func (change Change) Registration() enrollment.Registration { return change.registration }

// RequestHash returns the semantic replay binding for the intent.
func (change Change) RequestHash() registration.RequestHash { return change.requestHash }

// EvidenceIDs returns the stable authority evidence identities.
func (change Change) EvidenceIDs() EvidenceIDs { return change.evidenceIDs }

// OccurredAt returns the stable decision time shared across retries.
func (change Change) OccurredAt() time.Time { return change.occurredAt }

// IsValid reports whether every pending mutation invariant holds.
func (change Change) IsValid() bool {
	if !change.command.IsValid() || !change.registration.IsValid() ||
		change.registration.State() != enrollment.RegistrationStatePending ||
		!change.requestHash.IsValid() || !change.evidenceIDs.IsValid() || change.occurredAt.IsZero() {
		return false
	}
	hash, err := change.command.RequestHash()
	if err != nil || hash != change.requestHash {
		return false
	}
	return change.registration.ID() == change.command.RegistrationID &&
		change.registration.Scope() == change.command.Scope &&
		change.registration.MachineFingerprint() == change.command.Identity.MachineKey().Fingerprint() &&
		change.registration.CreatedAt().Equal(change.occurredAt)
}
