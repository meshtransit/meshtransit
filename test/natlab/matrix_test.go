var update = flag.Bool("update", false, "rewrite testdata/matrix.md")

const (
	matrixPath   = "testdata/matrix.md"
	pairTimeout  = 3 * time.Second
	retryTimeout = 8 * time.Second // a relay verdict is confirmed once with more time
	relayVerdict = TechniqueNone
)

// TestTraversalMatrix runs the reference agent for every pair of profiles and
// compares the techniques that found a path with testdata/matrix.md.
func TestTraversalMatrix(t *testing.T) {
	if testing.Short() {
		t.Skip("traversal matrix takes a few seconds")
	}
	profiles := Profiles()
	var (
		mu      sync.Mutex
		results = make(map[[2]string]Technique)
	)
	t.Run("pairs", func(t *testing.T) {
		for i, pa := range profiles {
			for _, pb := range profiles[i:] {
				t.Run(pa.Name+"/"+pb.Name, func(t *testing.T) {
					t.Parallel()
					got := traverse(t, pa, pb, pairTimeout)
					if got == relayVerdict {
						// Guard against a loaded machine: confirm with more time.
						got = traverse(t, pa, pb, retryTimeout)
					}
					mu.Lock()
					results[[2]string{pa.Name, pb.Name}] = got
					mu.Unlock()
				})
			}
		}
	})
	got := renderMatrix(profiles, results)
	if *update {
		if err := os.WriteFile(matrixPath, got, 0o600); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(filepath.Clean(matrixPath))
	if err != nil {
		t.Fatalf("%v (run with -update to create it)", err)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("traversal matrix changed; review and run with -update:\n%s", got)
	}
}

// traverse returns the technique that connected a pair, or relayVerdict.
func traverse(t *testing.T, pa, pb Profile, timeout time.Duration) Technique {
	t.Helper()
	lab, err := NewLab(nil)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(lab.Close)
	a := newAgent(t, lab, "a", pa)
	b := newAgent(t, lab, "b", pb)
	if err := a.Introduce(b.cfg.Disco.Public(), b.cfg.Node); err != nil {
		t.Fatal(err)
	}
	if err := b.Introduce(a.cfg.Disco.Public(), a.cfg.Node); err != nil {
		t.Fatal(err)
	}
	ra, rb, err := Pair(context.Background(), a, b, timeout)
	if err != nil {
		t.Fatal(err)
	}
	if (ra.Technique == relayVerdict) != (rb.Technique == relayVerdict) {
		t.Fatalf("one-sided path: a=%+v b=%+v", ra, rb)
	}
	if ra.Technique == relayVerdict {
		return relayVerdict
	}
	if ra.Remote.Addr() == LANHost || rb.Remote.Addr() == LANHost {
		t.Fatalf("path through a private address of the other LAN: a=%+v b=%+v", ra, rb)
	}
	return max(ra.Technique, rb.Technique)
}

func newAgent(t *testing.T, lab *Lab, name string, p Profile) *Agent {
	t.Helper()
	host, err := lab.AddNode(name, p)
	if err != nil {
		t.Fatal(err)
	}
	dk, err := key.NewDiscoPrivate()
	if err != nil {
		t.Fatal(err)
	}
	var node key.NodePublic
	copy(node[:], name+strings.Repeat("-", len(node)))
	a, err := NewAgent(AgentConfig{Host: host, Disco: dk, Node: node, STUN: lab.STUN(), Seed: seed(name, p.Name)})
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(a.Close)
	return a
}

func renderMatrix(profiles []Profile, results map[[2]string]Technique) []byte {
	var b bytes.Buffer
	b.WriteString("<!-- Generated by `go test ./test/natlab -run TestTraversalMatrix -update`. Do not edit. -->\n\n")
	b.WriteString("# Traversal matrix\n\n")
	b.WriteString("Technique with which the reference agent found a direct path; `relay` means none.\n\n")
	b.WriteString("| |")
	for _, p := range profiles {
		fmt.Fprintf(&b, " %s |", p.Name)
	}
	b.WriteString("\n|---|")
	b.WriteString(strings.Repeat("---|", len(profiles)))
	b.WriteString("\n")
	for i, pa := range profiles {
		fmt.Fprintf(&b, "| **%s** |", pa.Name)
		for j, pb := range profiles {
			k := [2]string{pa.Name, pb.Name}
			if j < i {
				k = [2]string{pb.Name, pa.Name}
			}
			fmt.Fprintf(&b, " %s |", results[k])
		}
		b.WriteString("\n")
	}
	return b.Bytes()
}

